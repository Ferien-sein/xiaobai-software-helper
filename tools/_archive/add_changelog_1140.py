# -*- coding: utf-8 -*-
"""给 CHANGELOG 加 v1.14.0。单独成文件，避免 PowerShell here-string 吃掉 $ 符号。"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
p = os.path.join(ROOT, "CHANGELOG.md")
s = io.open(p, encoding="utf-8", newline=None).read()

ENTRY = """---

## v1.14.0

### 新增：问卷先问「你要做的是哪一种」（程序 / 插件 / 脚本）
- 用户反馈原话：「想创建一个新的 DSH 插件，之后的问题好多都不适配」。
  现在第 1 题先问类型，选了插件就**换一整套题**：
  - 去掉「系统与位数」「在哪里打开」「怎么交付」——做插件不该被问 exe / 32 位 / apk
  - 换成插件专属的：**挂在哪个软件里**、怎么触发、要不要跟被挂的软件交换信息、
    要不要设置界面、怎么装上给谁用
  - 插件核心三题排在**第 3~5 位**（不塞到最后 —— 填到第 12 题才被问「你在做插件吗」早放弃了）
- 脚本类型同理：去掉交付类问题，加「怎么运行」
- 示例也跟着换：第 3 题的示例直接举 `DeepSeek Harness（DSH）桌面版，我在设置里装插件`

### 修复：换类型时崩溃 + 丢内容
- `_restore_selection` 会对**新一轮已不存在**的题调用 `_sync_options_to_box`
  → `KeyError: 'system'`（切到插件时实测崩过）。现在跳过不在当前题集里的题。
- 程序化写入输入框时前景色还停在占位符色，`collect()` 会把内容当成
  「用户还没填」丢掉 → 换类型后已填内容消失。
  新增 `_set_box_text()` 统一处理（真实用户点进去会触发 FocusIn 所以遇不到，
  但重建表单 / 载入存档 / 演示填充都必须自己处理这一步）。

### 修复：题号与语言包键写死编号
- **题号会随类型变**（插件集里「给谁用」是第 6 题、程序集是第 3 题），
  但语言包的键写着旧编号（"3. 给谁用？…"）→ 换类型后那条翻译失效，
  英文界面里冒出中文标题。
- 改法：题号不再写进基础标题和语言包键，由 `questions_for()` 按位置统一加；
  `i18n.t()` 查表时剥掉编号、查到后把**传入的**编号补回去。
- 附带修掉一个真 bug：`t()` 靠 `out != text` 判断是否命中，而 `_lookup` 会
  `lstrip()`，导致**每句都被当成命中**，第 2 题的编号因此丢失。

### 修复：界面提示说错了
- 因「类型」而变的题原来标「已按你的平台调整」，现在区分
  「已按你的类型调整」/「已按你的平台调整」。

### 检查口径再次扩展（第四个盲区）
- `check_i18n.py` 原来只扫 `A.QUESTIONS` 和平台自适应派生文案，
  **看不见「按类型组装出来的题集」**（插件 / 脚本专属题目）。
  扩口径后立刻抓出 25 条假 100%，已全部补上。
- 新增 `tools/fill_kind_i18n.py`（类型分支译文）、
  `tools/migrate_numbered_keys.py`（写死编号的键迁移成中性键）。
- 覆盖率：337 → **420 个键，100%**。

### 环境变量
- 新增 `XBSH_AUTOKIND=插件` 预设第 1 题类型（截图验证用，走真实点击路径）

"""

if "## v1.14.0" in s:
    print("  已有 v1.14.0")
else:
    i = s.index("---\n\n## v1.13.0")
    s = s[:i] + ENTRY + s[i + 4:]
    io.open(p, "w", encoding="utf-8", newline="\r\n").write(s)
    print("  CHANGELOG 已插入 v1.14.0")
