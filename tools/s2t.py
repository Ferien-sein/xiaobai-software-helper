def to_traditional(text):
    """简 → 繁。先做词汇级替换，再逐字替换剩余的字。"""
    if not isinstance(text, str):
        return text
    out = text
    for a, b in PHRASES:
        if a in out:
            out = out.replace(a, b)
    return "".join(S2T.get(c, c) for c in out)
